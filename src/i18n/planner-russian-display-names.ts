function readRussianDisplayName(
  displayNamesByKey: Readonly<Record<string, string>>,
  receivedKey: string,
  keyName: string,
): string {
  if (typeof receivedKey !== "string" || receivedKey.length === 0) {
    throw new TypeError(
      `${keyName} must be a non-empty string; received ${JSON.stringify(receivedKey)}.`,
    );
  }
  if (!Object.hasOwn(displayNamesByKey, receivedKey)) {
    throw new Error(
      `${keyName} ${JSON.stringify(receivedKey)} has no Russian display name.`,
    );
  }
  const russianDisplayName = displayNamesByKey[receivedKey];
  if (russianDisplayName === undefined || russianDisplayName.length === 0) {
    throw new Error(
      `${keyName} ${JSON.stringify(receivedKey)} has an empty Russian display name.`,
    );
  }
  return russianDisplayName;
}

