const catalogSidebarReferenceByItemId = new Map<string, CatalogSidebarReferenceEntry>();

for (const [category, referenceRows] of Object.entries(catalogSidebarReferenceRowsByCategory) as [CatalogSidebarCategory, readonly CatalogSidebarReferenceRow[]][]) {
  for (const [itemId, displayName, order, facetId, outdoors, indoors] of referenceRows) {
    if (itemId.length === 0 || displayName.length === 0 || !Number.isInteger(order) || facetId.length === 0) {
      throw new Error(`Invalid catalog sidebar reference row for item ID ${JSON.stringify(itemId)}.`);
    }
    if (catalogSidebarReferenceByItemId.has(itemId)) {
      throw new Error(`Duplicate catalog sidebar reference item ID ${JSON.stringify(itemId)}.`);
    }
    catalogSidebarReferenceByItemId.set(itemId, { displayName, category, order, facetId, outdoors, indoors });
  }
}

export function getCatalogSidebarReferenceEntry(
  itemId: string,
): CatalogSidebarReferenceEntry | undefined {
  if (typeof itemId !== "string" || itemId.length === 0) {
    throw new TypeError(`Catalog sidebar reference ID must be a non-empty string; received ${JSON.stringify(itemId) ?? String(itemId)}.`);
  }

  return catalogSidebarReferenceByItemId.get(itemId);
}
