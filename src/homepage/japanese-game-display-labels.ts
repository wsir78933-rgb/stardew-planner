export function readLocalizedCatalogItemLabel(
  locale: HomepageLocale,
  englishName: string,
): string {
  const catalogDisplayName = requireCatalogDisplayName(englishName);
  if (locale === "en" || locale === "zh-CN" || locale === "ru") {
    return catalogDisplayName;
  }
  if (locale === "ja") {
    return readJapaneseGameDisplayLabel(catalogDisplayName);
  }

  const unsupportedLocale: never = locale;
  throw new Error(
    `Catalog display locale is not supported. Received: ${JSON.stringify(unsupportedLocale)}.`,
  );
}

export function readSelectionEntityDisplayName(
  plannerChromeLocale: PlannerChromeLocale,
  entityName: string,
  catalogDisplayName?: string,
): string {
  const homepageLocale = readSelectionHomepageLocale(plannerChromeLocale);
  const validatedEntityName = requireCatalogDisplayName(entityName);
  const lookupName = catalogDisplayName === undefined
    ? validatedEntityName
    : requireCatalogDisplayName(catalogDisplayName);
  if (homepageLocale === "en" || homepageLocale === "zh-CN" || homepageLocale === "ru") {
    return readLocalizedCatalogItemLabel(homepageLocale, validatedEntityName);
  }
  if (homepageLocale === "ja") {
    if (catalogDisplayName === undefined) {
      return validatedEntityName;
    }
    return readLocalizedCatalogItemLabel("ja", lookupName);
  }

  const unsupportedHomepageLocale: never = homepageLocale;
  throw new Error(
    `Selection display locale is not supported. Received: ${JSON.stringify(unsupportedHomepageLocale)}.`,
  );
}

function readSelectionHomepageLocale(
  plannerChromeLocale: PlannerChromeLocale,
): HomepageLocale {
  if (plannerChromeLocale === "en") {
    return "en";
  }
  if (plannerChromeLocale === "zh") {
    return "zh-CN";
  }
  if (plannerChromeLocale === "ja") {
    return "ja";
  }
  if (plannerChromeLocale === "ru") {
    return "ru";
  }

  const unsupportedPlannerChromeLocale: never = plannerChromeLocale;
  throw new Error(
    `Cannot map selection display locale because planner chrome locale is ${JSON.stringify(unsupportedPlannerChromeLocale)}.`,
  );
}

function requireCatalogDisplayName(englishName: string): string {
  if (typeof englishName !== "string" || englishName.trim().length === 0) {
    throw new TypeError(
      `Catalog display name must be a non-empty string. Received: ${JSON.stringify(englishName)}.`,
    );
  }
  return englishName;
}

function readJapaneseGameDisplayLabel(englishName: string): string {
  if (!Object.hasOwn(japaneseGameDisplayLabelByEnglishName, englishName)) {
    throw new Error(
      `Japanese catalog display name is missing for ${JSON.stringify(englishName)}. Received: ${JSON.stringify(englishName)}.`,
    );
  }

  return japaneseGameDisplayLabelByEnglishName[englishName];
}
