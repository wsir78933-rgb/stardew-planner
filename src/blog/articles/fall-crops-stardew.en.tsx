      <p>
        Planted on Fall 1, grow times exclude the plant day, so the first pick
        is Fall 11, then every 3 days: 14, 17, 20, 23, and 26. That is six picks
        and matches the wiki maximum. The tile is still grape on Fall 14 when a
        pumpkin cycle finishes, and it is still grape through Fall 28 even
        though the sixth pick already landed on 26.
      </p>
